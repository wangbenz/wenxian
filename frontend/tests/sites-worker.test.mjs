test("keeps implementation details out of player-facing copy", async () => {
  const prototype = await readFile(new URL("../src/Prototype.tsx", import.meta.url), "utf8");
  const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
  const forbiddenCopy = [
    "DeepSeek Agent 已连接",
    "Agent 负责叙事裁决",
    "Java 负责规则",
    "V4 PRO · 命卷推演中",
    "DeepSeek 正在推演",
    "DeepSeek 已推演",
    "启动 Java 服务",
    "恢复后端后才能继续行动",
    "Agent 只会在固定世界内调整开局",
    "由服务器沿同一时间轴保存",
    "Agent 修仙文字游戏",
  ];

  for (const copy of forbiddenCopy) {
    assert.equal(prototype.includes(copy) || html.includes(copy), false, `player copy leaked: ${copy}`);
  }
});
